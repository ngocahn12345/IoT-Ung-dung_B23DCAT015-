export interface SensorDataRecord {
  id: string;
  sensorName: string;
  sensorType: "TEMPERATURE" | "HUMIDITY" | "LIGHT" | "GAS" | string;
  room: string;
  value: number;
  unit: string;
  timestamp: string;
  status: "NORMAL" | "WARNING" | "CRITICAL";
  topic: string;
  rawPayload: Record<string, unknown>;
}

export interface ActionRecord {
  id: string;
  deviceId: string;
  deviceName: string;
  deviceType: "FAN" | "LIGHT" | "AC" | "ALARM" | string;
  action: "ON" | "OFF" | "AUTO";
  status: "ON" | "OFF" | "LOADING";
  sentTime: string; // TG gửi lệnh (TG bật)
  responseTime: string; // TG phản hồi từ Hardware ACK
  performedBy: string; // User / Automation
  detail: string;
}

export interface AutomationRule {
  id: string;
  name: string;
  room: string;
  sensorType: string;
  operator: ">" | "<" | "=" | "≥" | "≤";
  thresholdValue: number;
  unit: string;
  targetDevice: string;
  actionOnTrigger: "ON" | "OFF";
  isActive: boolean;
  lastTriggered?: string;
}

